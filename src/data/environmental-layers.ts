/**
 * DEMO environmental layers.
 * Intensities are synthetic placeholders for UI demonstration only.
 * Metadata points to real authoritative organizations as intended future sources —
 * the numeric values themselves are NOT from those datasets.
 */

function demoIntensities(
  seed: number,
  bias: Record<string, number> = {}
): Record<string, number> {
  const out: Record<string, number> = {};
  US_STATES.forEach((s, i) => {
    if (bias[s.code] !== undefined) {
      out[s.code] = bias[s.code];
      return;
    }
    // Deterministic pseudo-random 0.05–0.95 for demo coloring
    const x = Math.sin(seed * 12.9898 + i * 78.233) * 43758.5453;
    out[s.code] = 0.05 + (x - Math.floor(x)) * 0.9;
  });
  return out;
}

